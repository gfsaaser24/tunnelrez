"""Write version.rs from the `#define NV*_VER` macros of nvEncodeAPI.h (bindgen skips function-like macros).

    python genver.py <nvEncodeAPI.h> <version.rs>
"""
import re
import sys

hdr, out = sys.argv[1], sys.argv[2]
src = open(hdr, encoding="utf-8", errors="replace").read()
rows = []
for name, expr in re.findall(r"^#define\s+(NV\w*_VER)\s+(.+?)\s*$", src, re.M):
    m = re.fullmatch(r"\(?\s*NVENCAPI_STRUCT_VERSION\((\d+)\)\s*(\|\s*\(\s*1u\s*<<\s*31\s*\))?\s*\)?", expr)
    if not m:
        raise SystemExit(f"unknown version macro form: {name} {expr}")
    v = f"NVENCAPI_STRUCT_VERSION({m.group(1)})" + (" | (1 << 31)" if m.group(2) else "")
    rows.append(f"pub const {name}: u32 = {v};")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("//! Struct version constants of `nvEncodeAPI.h` (generated by genver.py; bindgen skips these macros).\n\n")
    f.write("/// `NVENCAPI_STRUCT_VERSION(ver)` from the header.\n#[must_use]\n#[allow(non_snake_case)]\n")
    f.write("pub const fn NVENCAPI_STRUCT_VERSION(ver: u32) -> u32 {\n")
    f.write("    super::api::NVENCAPI_VERSION | (ver << 16) | (0x7 << 28)\n}\n\n")
    f.write("\n".join(rows) + "\n")
print(f"wrote {out}: {len(rows)} constants")
