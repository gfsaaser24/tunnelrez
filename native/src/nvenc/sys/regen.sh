#!/bin/bash
# Regenerate api.rs and version.rs (raw NVENC bindings) from NVIDIA's nvEncodeAPI.h. Current: API 13.1.
# PINNED: see docs/PINNED.md (NVENC SDK 13.1 headers, tag n13.1.15.0)
#
#   regen.sh <path/to/nvEncodeAPI.h> <dir with libclang.dll>
#
# Header: FFmpeg nv-codec-headers tag n13.1.15.0 (mirror of the Video Codec SDK 13.1 header),
#   https://raw.githubusercontent.com/FFmpeg/nv-codec-headers/n13.1.15.0/include/ffnvcodec/nvEncodeAPI.h
# Tools: `cargo install bindgen-cli`; libclang.dll e.g. from `python -m pip download libclang` (wheel = zip).
#
# C enums become integer newtypes (`--newtype-enum`), so an all-zero struct is a valid Rust value
# (`nvenc::zeroed`). version.rs is generated by genver.py from the `NV*_VER` macros (bindgen skips
# function-like macros). guid.rs is hand-kept: bindgen cannot emit the GUID statics.
set -euo pipefail
HDR=$1
export LIBCLANG_PATH=$2
DIR=$(dirname "$0")
bindgen "$HDR" \
  --use-core \
  --newtype-enum '.*' \
  --allowlist-type 'NV.*|_NV.*|PNV.*|GUID|_GUID' \
  --allowlist-var 'NV.*' \
  --blocklist-var '.*_GUID' \
  --with-derive-default \
  --raw-line 'pub use super::{guid::*, version::*};' \
  --output "$DIR/api.rs" \
  -- -x c --target=x86_64-pc-windows-msvc
echo "wrote $DIR/api.rs"
python "$DIR/genver.py" "$HDR" "$DIR/version.rs"
