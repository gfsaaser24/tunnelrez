//! `IPolicyConfig`: the undocumented COM interface that Windows' own Sound settings use to change the default
//! playback device and an endpoint's format. Sunshine and Apollo use it the same way (Windows 7 and later).

use anyhow::{Context, Result};
use windows::core::PCWSTR;
use windows::Win32::Media::Audio::{ERole, WAVEFORMATEX};
use windows::Win32::System::Com::{CoCreateInstance, CoTaskMemFree, CLSCTX_ALL};
use windows_core::GUID;

/// `CLSID_CPolicyConfigClient`.
const CLSID_POLICY_CONFIG: GUID = GUID::from_u128(0x870a_f99c_171d_4f9e_af0d_e63d_f40c_2bc9);

/// The raw interface. The macro's generated code trips two clippy lints, so it lives in its own module.
#[expect(clippy::transmute_ptr_to_ptr, reason = "generated by windows_core::interface")]
mod raw {
    use windows::core::{HRESULT, PCWSTR};
    use windows::Win32::Media::Audio::{ERole, WAVEFORMATEX};
    use windows_core::{IUnknown, IUnknown_Vtbl};

    /// The vtable order is fixed by Windows; only `GetDeviceFormat`, `SetDeviceFormat` and `SetDefaultEndpoint` are
    /// called. The other slots keep the layout.
    #[windows_core::interface("f8679f50-850a-41cf-9c72-430f290290c8")]
    pub unsafe trait IPolicyConfig: IUnknown {
        pub unsafe fn get_mix_format(&self, id: PCWSTR, format: *mut *mut WAVEFORMATEX) -> HRESULT;
        pub unsafe fn get_device_format(&self, id: PCWSTR, default: i32, format: *mut *mut WAVEFORMATEX) -> HRESULT;
        pub unsafe fn reset_device_format(&self, id: PCWSTR) -> HRESULT;
        pub unsafe fn set_device_format(
            &self,
            id: PCWSTR,
            endpoint: *const WAVEFORMATEX,
            mix: *const WAVEFORMATEX,
        ) -> HRESULT;
        pub unsafe fn get_processing_period(&self, id: PCWSTR, default: i32, def: *mut i64, min: *mut i64) -> HRESULT;
        pub unsafe fn set_processing_period(&self, id: PCWSTR, period: *const i64) -> HRESULT;
        pub unsafe fn get_share_mode(&self, id: PCWSTR, mode: *mut u32) -> HRESULT;
        pub unsafe fn set_share_mode(&self, id: PCWSTR, mode: *const u32) -> HRESULT;
        pub unsafe fn get_property_value(&self, id: PCWSTR, fx: i32, key: *const u8, value: *mut u8) -> HRESULT;
        pub unsafe fn set_property_value(&self, id: PCWSTR, fx: i32, key: *const u8, value: *const u8) -> HRESULT;
        pub unsafe fn set_default_endpoint(&self, id: PCWSTR, role: ERole) -> HRESULT;
        pub unsafe fn set_endpoint_visibility(&self, id: PCWSTR, visible: i32) -> HRESULT;
    }
}

use raw::IPolicyConfig;

/// A policy-config client. Create and use it on a thread with COM initialized.
#[derive(Debug)]
pub struct Policy(IPolicyConfig);

fn wide(s: &str) -> Vec<u16> {
    s.encode_utf16().chain(std::iter::once(0)).collect()
}

impl Policy {
    /// # Errors
    ///
    /// The class is not registered (a Windows build without it).
    pub fn new() -> Result<Policy> {
        // SAFETY: plain COM activation of a system class; COM is initialized on this thread (see `wasapi::Com`).
        let p: IPolicyConfig = unsafe { CoCreateInstance(&CLSID_POLICY_CONFIG, None, CLSCTX_ALL) }
            .context("CPolicyConfigClient (default-device control)")?;
        Ok(Policy(p))
    }

    /// Make endpoint `id` the default playback device for `role`.
    ///
    /// # Errors
    ///
    /// The device is gone, or Windows refused.
    pub fn set_default(&self, id: &str, role: ERole) -> Result<()> {
        let w = wide(id);
        // SAFETY: `w` is NUL-terminated and outlives the call; the role is a valid ERole.
        unsafe { self.0.set_default_endpoint(PCWSTR(w.as_ptr()), role) }
            .ok()
            .with_context(|| format!("set default playback device ({}) to {id}", role.0))
    }

    /// The endpoint's device format (the "Default Format" in Sound settings), as raw `WAVEFORMATEX(TENSIBLE)`
    /// bytes.
    ///
    /// # Errors
    ///
    /// The device is gone, or has no stored format.
    pub fn device_format(&self, id: &str) -> Result<Vec<u8>> {
        let w = wide(id);
        let mut p: *mut WAVEFORMATEX = std::ptr::null_mut();
        // SAFETY: valid NUL-terminated id and out-pointer; the result is a CoTaskMem block freed below.
        unsafe { self.0.get_device_format(PCWSTR(w.as_ptr()), 0, &raw mut p) }.ok().context("GetDeviceFormat")?;
        if p.is_null() {
            anyhow::bail!("GetDeviceFormat returned null");
        }
        // SAFETY: `p` points to a WAVEFORMATEX (possibly unaligned) plus `cbSize` extra bytes.
        let len = std::mem::size_of::<WAVEFORMATEX>() + usize::from(unsafe { p.read_unaligned() }.cbSize);
        // SAFETY: the block is `len` bytes long and stays valid until freed below.
        let bytes = unsafe { std::slice::from_raw_parts(p.cast::<u8>(), len) }.to_vec();
        // SAFETY: allocated by COM for us; freed once, not used after.
        unsafe { CoTaskMemFree(Some(p.cast::<std::ffi::c_void>().cast_const())) };
        Ok(bytes)
    }

    /// Set the endpoint's device format (raw `WAVEFORMATEX(TENSIBLE)` bytes). The engine's mix format follows it
    /// (same rate and channels, float).
    ///
    /// # Errors
    ///
    /// The format is too short, the device does not take it, or Windows refused.
    pub fn set_device_format(&self, id: &str, format: &[u8]) -> Result<()> {
        if format.len() < std::mem::size_of::<WAVEFORMATEX>() {
            anyhow::bail!("format too short ({} bytes)", format.len());
        }
        let w = wide(id);
        // Copies: the API is undocumented, so it gets its own buffers (as Sunshine does), 8-byte aligned.
        let mut fmt = vec![0u64; format.len().div_ceil(8)];
        // SAFETY: `fmt` holds at least `format.len()` bytes; the regions do not overlap.
        unsafe { std::ptr::copy_nonoverlapping(format.as_ptr(), fmt.as_mut_ptr().cast::<u8>(), format.len()) };
        let mut mix = vec![0u64; 64 / 8];
        // SAFETY: valid id; `fmt` is a complete WAVEFORMATEX(TENSIBLE); `mix` is a zeroed 64-byte scratch block
        // (Sunshine passes an empty WAVEFORMATEXTENSIBLE there).
        unsafe {
            self.0.set_device_format(
                PCWSTR(w.as_ptr()),
                fmt.as_ptr().cast::<WAVEFORMATEX>(),
                mix.as_mut_ptr().cast::<WAVEFORMATEX>().cast_const(),
            )
        }
        .ok()
        .context("SetDeviceFormat")
    }
}

/// `WAVEFORMATEXTENSIBLE` bytes for 48 kHz 16-bit stereo PCM: the stream format, so the engine neither
/// resamples nor downmixes on the sink.
pub fn stereo_48k_s16() -> Vec<u8> {
    const KSDATAFORMAT_SUBTYPE_PCM_TAIL: [u8; 12] =
        [0x00, 0x00, 0x10, 0x00, 0x80, 0x00, 0x00, 0xAA, 0x00, 0x38, 0x9B, 0x71];
    let (ch, rate, bits) = (2u16, 48_000u32, 16u16);
    let block = ch * bits / 8;
    let mut b = Vec::with_capacity(40);
    b.extend_from_slice(&0xFFFEu16.to_le_bytes()); // WAVE_FORMAT_EXTENSIBLE
    b.extend_from_slice(&ch.to_le_bytes());
    b.extend_from_slice(&rate.to_le_bytes());
    b.extend_from_slice(&(rate * u32::from(block)).to_le_bytes());
    b.extend_from_slice(&block.to_le_bytes());
    b.extend_from_slice(&bits.to_le_bytes());
    b.extend_from_slice(&22u16.to_le_bytes()); // cbSize
    b.extend_from_slice(&bits.to_le_bytes()); // wValidBitsPerSample
    b.extend_from_slice(&3u32.to_le_bytes()); // SPEAKER_FRONT_LEFT | SPEAKER_FRONT_RIGHT
    b.extend_from_slice(&1u32.to_le_bytes()); // SubFormat Data1 = PCM
    b.extend_from_slice(&KSDATAFORMAT_SUBTYPE_PCM_TAIL);
    b
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::audio::pcm::Sample;
    use crate::audio::wasapi::parse_wave_format;

    #[test]
    fn the_sink_format_is_48k_s16_stereo() {
        let b = stereo_48k_s16();
        assert_eq!(b.len(), 40);
        let f = parse_wave_format(&b).expect("our own format parses");
        assert_eq!((f.rate, f.sample, f.channels(), f.block_align), (48_000, Sample::I16, 2, 4));
    }
}
